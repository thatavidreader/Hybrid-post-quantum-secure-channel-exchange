"""Render docs/test_matrix.md from results/test_results.json (written by pytest).

Run:  python -m pytest && python tests/make_test_matrix.py
Nothing in the table is typed by hand: "Actual" is what the test itself observed.
"""
from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    results = json.loads((ROOT / "results" / "test_results.json").read_text())
    total = len(results)
    passed = sum(r["outcome"] == "passed" for r in results)
    rows = []
    for r in results:
        if not r["matrix"]:
            continue
        tid, attack, expected = r["matrix"]
        name = r["nodeid"].split("::", 1)[1]
        verdict = "PASS" if r["outcome"] == "passed" else "FAIL"
        rows.append((int(re.sub(r"\D", "", tid)), name, tid, attack, expected, r["actual"], verdict))
    rows.sort(key=lambda x: (x[0], x[1]))
    backend = results[0]["backend"] if results else "?"
    lines = [
        "# Test matrix",
        "",
        f"Generated by `tests/make_test_matrix.py` from a real pytest run on "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M')} (ML-KEM backend: `{backend}`).",
        f"Whole suite: **{passed}/{total} tests passed** (the table lists the scenario tests; "
        "the remaining tests are unit/control tests in `tests/`).",
        "",
        "| ID | Test | Attack / condition | Expected | Actual (observed in the run) | Result |",
        "|----|------|--------------------|----------|------------------------------|--------|",
    ]
    for _, name, tid, attack, expected, actual, verdict in rows:
        esc = lambda s: s.replace("|", "\\|")
        lines.append(f"| {tid} | `{name}` | {esc(attack)} | {esc(expected)} | {esc(actual)} | **{verdict}** |")
    # Full inventory: every test, grouped by file, so the 46/46 coverage claim is checkable.
    by_file: dict[str, list[dict]] = {}
    for r in results:
        by_file.setdefault(r["nodeid"].split("::", 1)[0], []).append(r)
    lines += ["", "## Full test inventory", "",
              "| Test file | Tests | Passed | Test names |", "|---|---|---|---|"]
    for path, rs in sorted(by_file.items()):
        names = ", ".join(f"`{r['nodeid'].split('::', 1)[1]}`" for r in rs)
        lines.append(f"| `{path}` | {len(rs)} | {sum(r['outcome'] == 'passed' for r in rs)} | {names} |")
    (ROOT / "docs" / "test_matrix.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/test_matrix.md ({len(rows)} scenario rows, {passed}/{total} passed)")


if __name__ == "__main__":
    main()
